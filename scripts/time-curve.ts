// Writes app/src/time/curve.ts, the curve from watching time to history time
// (spec section 2.1). Run it only to change the curve: `node scripts/time-curve.ts`.
//
// The rate of history, in years per minute of watching at regular speed, is the
// age before the end of the timeline divided by a constant, so each factor of ten
// of the past takes the same watching time; nudged by a rough, heavily smoothed
// density of the era boundaries in data/curated/eras (busier stretches a little
// slower, by the square root); never below one year per minute; and scaled so the
// whole timeline takes exactly 24 hours.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DAYS_PER_YEAR, TIMELINE_END, TIMELINE_START } from '../app/src/time/calendar.ts';
import { parseDate } from '../data/build/lib/records.ts';

const ROOT = join(import.meta.dirname, '..');
const TOTAL_MS = 24 * 60 * 60 * 1000;
const KNOTS = 512;
/** Never slower than this many years per minute. */
const FLOOR = 1;
/** Ages are counted from the end of the timeline plus this many years, so the log stays finite. */
const AGE0 = 50;
/** Smoothing of the density, in natural-log units of age: about a factor of 1.5 each way. */
const SIGMA = 0.4;
/** How strongly density slows the rate, and the bounds of that nudge. */
const POWER = 0.5;
const NUDGE: [number, number] = [0.6, 1.6];

const START = TIMELINE_START;
const END = TIMELINE_END;
const ageOf = (day: number) => (END - day) / DAYS_PER_YEAR;
const u = (day: number) => Math.log(ageOf(day) + AGE0);

// Era boundaries, from and to, as days.
const marks: number[] = [];
const dir = join(ROOT, 'data/curated/eras');
for (const file of readdirSync(dir).filter((f) => f.endsWith('.md'))) {
  const text = readFileSync(join(dir, file), 'utf8');
  for (const key of ['from', 'to']) {
    const m = new RegExp(`^\\s+${key}:\\s*(.+)$`, 'm').exec(text);
    const d = m && parseDate(m[1]!.replace(/^['"]|['"]$/g, ''), START, END);
    if (d && d.first > START && d.first < END) marks.push(d.first);
  }
}

// Density in log-age, smoothed, relative to its mean over the timeline.
const uMin = u(END);
const uMax = u(START);
const BINS = 400;
const density = new Float64Array(BINS);
for (let b = 0; b < BINS; b++) {
  const at = uMin + ((b + 0.5) / BINS) * (uMax - uMin);
  for (const d of marks) density[b]! += Math.exp(-0.5 * ((u(d) - at) / SIGMA) ** 2);
}
const mean = density.reduce((a, b) => a + b, 0) / BINS;
const nudgeAt = (day: number) => {
  const b = Math.min(BINS - 1, Math.max(0, Math.floor(((u(day) - uMin) / (uMax - uMin)) * BINS)));
  const n = (mean / Math.max(density[b]!, mean * 1e-3)) ** POWER;
  return Math.min(NUDGE[1], Math.max(NUDGE[0], n));
};

/** Years per minute at a day for a constant c. */
const rate = (day: number, c: number) => Math.max(FLOOR, (ageOf(day) / c) * nudgeAt(day));

// Fine samples, crowded towards the end where the days pass slowly: (1 - f)^4 runs from
// 1 at the start to 0 at the end.
const SAMPLES = 200_000;
const days: number[] = [];
for (let k = 0; k <= SAMPLES; k++) days.push(END - (END - START) * (1 - k / SAMPLES) ** 4);

/** Cumulative watching milliseconds at each sample for a constant c. */
function watching(c: number): number[] {
  const out = [0];
  for (let k = 1; k < days.length; k++) {
    const d0 = days[k - 1]!;
    const d1 = days[k]!;
    const mid = (d0 + d1) / 2;
    const years = (d1 - d0) / DAYS_PER_YEAR;
    out.push(out[k - 1]! + (years / rate(mid, c)) * 60_000);
  }
  return out;
}

// Solve for c so the whole timeline takes TOTAL_MS.
let lo = 1;
let hi = 10_000;
for (let n = 0; n < 80; n++) {
  const c = Math.sqrt(lo * hi);
  // A larger c is a slower rate and a longer watch.
  if (watching(c).at(-1)! > TOTAL_MS) hi = c;
  else lo = c;
}
const c = Math.sqrt(lo * hi);
const w = watching(c);
const scale = TOTAL_MS / w.at(-1)!;

// Knots evenly spaced in watching time, at whole days, strictly increasing.
const knotMs: number[] = [];
const knotDays: number[] = [];
let k = 0;
for (let i = 0; i <= KNOTS; i++) {
  const ms = Math.round((i / KNOTS) * TOTAL_MS);
  while (k + 1 < w.length && w[k + 1]! * scale < ms) k++;
  const a = w[k]! * scale;
  const b = (w[k + 1] ?? w[k]!) * scale;
  const f = b > a ? (ms - a) / (b - a) : 0;
  let day = Math.round(days[k]! + f * ((days[k + 1] ?? days[k]!) - days[k]!));
  if (i === 0) day = START;
  if (i === KNOTS) day = END;
  if (knotDays.length && day <= knotDays.at(-1)!) day = knotDays.at(-1)! + 1;
  knotMs.push(ms);
  knotDays.push(day);
}

const fmt = (xs: number[]) => xs.map((x) => String(x)).join(', ');
writeFileSync(
  join(ROOT, 'app/src/time/curve.ts'),
  `// Generated by scripts/time-curve.ts from the era boundaries of data/curated/eras
// (spec section 2.1); do not edit. Watching time in milliseconds at regular speed and
// the history day there: ${KNOTS + 1} knots, evenly spaced in watching time, the last at
// exactly 24 hours. Between knots the day runs linearly (milestone 1, section 3.3).

/** The constant of the rate, age / c years per minute before the floor and the nudge. */
export const CURVE_C = ${c.toFixed(3)};

export const CURVE_MS: readonly number[] = [${fmt(knotMs)}];

export const CURVE_DAYS: readonly number[] = [${fmt(knotDays)}];
`,
);
console.log(`time-curve: ${marks.length} era boundaries, c = ${c.toFixed(1)}, ${KNOTS + 1} knots`);
